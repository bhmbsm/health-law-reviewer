const expand=(text:string,law:string):string[]=>{
 const map=law.startsWith('의료법')||law==='간호법'?medical:law==='국민건강보험법'?insurance:{};
 let values=[text];
 for(const [from,to]of Object.entries(map))values=values.flatMap(v=>v.includes(from)?(Array.isArray(to)?to:[to]).map(x=>v.split(from).join(x)):[v]);
 return values;
};
export function studentText(text:string,law:string):string{
 return expand(text,law).join(' 또는 ');
}
export function studentFact(value:unknown,law:string):unknown{
 if(typeof value!=='string')return value;
 const options=value.startsWith('RAND_CHOICE:')?value.slice(12).split(':'):[value];
 const expanded=options.flatMap(x=>expand(x,law));
 if(expanded.length===options.length&&expanded.every((x,i)=>x===options[i]))return value;
 return expanded.length>1?'RAND_CHOICE:'+expanded.join(':'):expanded[0];
}
/** Expand only student-facing facts and prose. Source text, references and answers stay intact. */
export function studentRule(rule:Rule):Rule{
 const facts=(rows:Record<string,unknown>[])=>rows.map(row=>Object.fromEntries(Object.entries(row).map(([k,v])=>[k,studentFact(v,rule.law)])));
 return {...rule,scenario:studentText(rule.scenario,rule.law),approveFacts:facts(rule.approveFacts),rejectFacts:facts(rule.rejectFacts)};
}
